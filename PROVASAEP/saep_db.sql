\encoding UTF8
-- Banco de dados do sistema VetCare (PostgreSQL).
-- Execute conectado ao banco configurado em sistema/config/database.ini.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tutor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(180) NOT NULL,
    telefone VARCHAR(30) NOT NULL DEFAULT '',
    endereco VARCHAR(250) NOT NULL DEFAULT '',
    cpf_criptografado BYTEA NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    especie VARCHAR(60) NOT NULL,
    raca VARCHAR(80),
    data_nascimento DATE,
    tutor_id BIGINT NOT NULL REFERENCES tutor(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS agendamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL REFERENCES pet(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    data_hora TIMESTAMP NOT NULL,
    motivo VARCHAR(200) NOT NULL DEFAULT 'Consulta',
    status VARCHAR(30) NOT NULL DEFAULT 'Agendado'
        CHECK (status IN ('Agendado', 'Confirmado', 'Concluído', 'Cancelado')),
    observacoes VARCHAR(1000),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_agendamento_data_hora ON agendamento (data_hora);
CREATE INDEX IF NOT EXISTS idx_pet_tutor_id ON pet (tutor_id);
CREATE INDEX IF NOT EXISTS idx_tutor_nome ON tutor (nome);

